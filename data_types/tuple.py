colors = ("Red", "Green", "Blue", "Red")

# Functions
print("Length:", len(colors))
print("Count of Red:", colors.count("Red"))
print("Index of Green:", colors.index("Green"))

#operators
t1 = (1,2,7,6,9)
t2 = (3, 4)
print(t1[0:4])    #slicing
print(t1 + t2)    # Concatenation
print(t1 * 2)     # Repetition
print(1 in t1)    # Membership